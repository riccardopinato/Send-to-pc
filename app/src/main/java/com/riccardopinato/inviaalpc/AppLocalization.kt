package com.riccardopinato.inviaalpc

import android.content.Context
import java.util.Locale

enum class AppLanguage(
    val code: String,
    val nativeName: String
) {
    EN("en", "English"),
    IT("it", "Italiano"),
    ES("es", "Español"),
    FR("fr", "Français"),
    DE("de", "Deutsch"),
    PT("pt", "Português");

    companion object {
        fun fromCode(code: String?): AppLanguage? =
            entries.firstOrNull {
                it.code.equals(
                    code,
                    ignoreCase = true
                )
            }
    }
}

object AppLanguageStore {
    private const val PREFS = "app_preferences"
    private const val KEY = "language_override"

    fun current(
        context: Context
    ): AppLanguage {
        val prefs =
            context.getSharedPreferences(
                PREFS,
                Context.MODE_PRIVATE
            )

        val override =
            AppLanguage.fromCode(
                prefs.getString(KEY, null)
            )

        if (override != null) {
            return override
        }

        val deviceCode =
            Locale.getDefault().language

        return AppLanguage.fromCode(
            deviceCode
        ) ?: AppLanguage.EN
    }

    fun overrideCode(
        context: Context
    ): String? =
        context.getSharedPreferences(
            PREFS,
            Context.MODE_PRIVATE
        ).getString(KEY, null)

    fun setOverride(
        context: Context,
        language: AppLanguage?
    ) {
        val editor =
            context.getSharedPreferences(
                PREFS,
                Context.MODE_PRIVATE
            ).edit()

        if (language == null) {
            editor.remove(KEY)
        } else {
            editor.putString(
                KEY,
                language.code
            )
        }

        editor.apply()
    }
}

