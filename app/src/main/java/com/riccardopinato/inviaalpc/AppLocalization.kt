    fun missingKeys(
        language: AppLanguage
    ): Set<String> =
        en.keys - mapFor(language).keys

    private fun mapFor(
        language: AppLanguage
    ): Map<String, String> =
        when (language) {
            AppLanguage.EN -> en
            AppLanguage.IT -> it
            AppLanguage.ES -> es
            AppLanguage.FR -> fr
            AppLanguage.DE -> de
            AppLanguage.PT -> pt
        }

    fun get(
        language: AppLanguage,
        key: String,
        vararg args: Any
    ): String {
        val template =
            mapFor(language)[key]
                ?: en[key]
                ?: key

        return if (args.isEmpty()) {
            template
        } else {
            String.format(
                Locale.forLanguageTag(
                    language.code
                ),
                template,
                *args
            )
        }
    }
